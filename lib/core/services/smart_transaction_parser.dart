      'dapat kiriman',
      'terima transfer',
      'bonus',
      'thr',
      'cashback',
      'komisi',
      'freelance',
      'proyek',
      'hasil jualan',
      'jual',
      'jualan',
      'laba',
      'profit',
      'omset',
      'omzet',
      'dividen',
      'hadiah',
      'gift',
      'angpao',
    ];
    for (final kw in incomeKeywords) {
      if (RegExp('\\b$kw\\b', caseSensitive: false).hasMatch(text)) {
        return true;
      }
    }
    return false;
  }

