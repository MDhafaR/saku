  /// Membersihkan nama kontak dari kata sambung
  String _cleanContactName(String? raw) {
    if (raw == null) return '';
    var name = raw.trim();
    // Buang preposisi di ujung
    name = name.replaceAll(RegExp(r'\s+(?:sebesar|sejumlah|senilai|rp|\d+).*$', caseSensitive: false), '');
    return name.trim();
  }

  /// Membersihkan kandidat nama wallet dari kata-kata umum
  String? _cleanWalletCandidate(String? raw) {
    if (raw == null) return null;
    final name = raw.replaceAll(RegExp(r'^(?:rekening|bank|dompet|akun|kartu)\s+', caseSensitive: false), '').trim();
    final lower = name.toLowerCase();
    const nonWalletWords = [
      'uang',
      'saldo',
      'sebesar',
      'sejumlah',
      'senilai',
      'rp',
      'ke',
      'dari',
      'saya',
      'kamu',
      'dia',
      'pindah',
      'transfer',
    ];
    if (nonWalletWords.contains(lower) || RegExp(r'^\d').hasMatch(lower)) {
      return null;
    }
    return name;
  }

  /// Ekstraksi wallet asal jika kalimat transfer tidak memiliki pola regex langsung
  String? _extractSourceWalletForTransfer(String text, {String? excludedWallet}) {
    // 1. Coba cari preposisi "dari [wallet]" atau "pakai [wallet]"
    final prepRegex = RegExp(
      r'\b(?:dari|pakai|pake|via|lewat|menggunakan|melalui)\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+|kartu\s+)?([A-Za-z0-9_]+)\b',
      caseSensitive: false,
    );
    final match = prepRegex.firstMatch(text);
    if (match != null) {
      final candidate = _cleanWalletCandidate(match.group(1));
      if (candidate != null && (excludedWallet == null || candidate.toLowerCase() != excludedWallet.toLowerCase())) {
        return candidate;
      }
    }

    // 2. Cek keyword wallet populer jika tidak sama dengan destination wallet
    const knownWallets = [
      'jago',
      'bca',
      'bri',
      'bni',
      'mandiri',
      'cimb',
      'permata',
      'seabank',
      'blu',
      'jenius',
      'bsi',
      'gopay',
      'gojek',
      'ovo',
      'dana',
      'shopeepay',
      'spay',
      'linkaja',
      'cash',
      'tunai',
      'dompet',
    ];
    for (final kw in knownWallets) {
      if (excludedWallet != null && kw.toLowerCase() == excludedWallet.toLowerCase()) {
        continue;
      }
      if (RegExp('\\b$kw\\b', caseSensitive: false).hasMatch(text)) {
        return kw;
      }
    }

    return null;
  }

  /// Ekstraksi nama rekening / wallet dari preposisi atau nama bank/e-wallet populer
  String? _extractWallet(String text) {
    // 1. Pola preposisi eksplisit: "dengan jago", "pakai bca", "pake gopay", "via ovo", "lewat dana", "dari dompet", "menggunakan spay", "pake rekening bni"
    final prepRegex = RegExp(
      r'\b(?:dengan|pakai|pake|via|lewat|menggunakan|by|melalui|dari)\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+|kartu\s+)?([A-Za-z0-9_]+(?:\s+[A-Za-z0-9_]+)?)\b',
      caseSensitive: false,
    );

    final match = prepRegex.firstMatch(text);
    if (match != null) {
      final candidate = match.group(1)!.trim();
      final lower = candidate.toLowerCase();
      const nonWalletWords = [
        'cepat',
        'mudah',
        'senang',
        'teman',
        'keluarga',
        'kawan',
        'uang',
        'rupiah',
        'sebesar',
        'sejumlah',
        'harga',
        'kemarin',
        'tadi',
        'malam',
        'siang',
        'pagi',
        'sore',
      ];
      if (!nonWalletWords.contains(lower) && !RegExp(r'^\d').hasMatch(lower)) {
        return _normalizeWalletName(candidate);
      }
    }

    // 2. Pola nama e-wallet / bank populer langsung jika ada di teks
    const knownWallets = [
      'jago',
      'bca',
      'bri',
      'bni',
      'mandiri',
      'cimb',
      'permata',
      'seabank',
      'blu',
      'jenius',
      'bsi',
      'gopay',
      'gojek',
      'ovo',
      'dana',
      'shopeepay',
      'spay',
      'linkaja',
      'cash',
      'tunai',
      'dompet',
    ];
    for (final kw in knownWallets) {
      if (RegExp('\\b$kw\\b', caseSensitive: false).hasMatch(text)) {
        return _normalizeWalletName(kw);
      }
    }

    return null;
  }

  /// Normalisasi nama wallet agar rapi dan kapitalisasi tepat
  String _normalizeWalletName(String raw) {
    final clean = raw.replaceAll(RegExp(r'^(?:rekening|bank|dompet|akun|kartu)\s+', caseSensitive: false), '').trim();
    final lower = clean.toLowerCase();
    switch (lower) {
      case 'jago':
      case 'bank jago':
        return 'Jago';
      case 'bca':
      case 'bank bca':
        return 'BCA';
      case 'bri':
      case 'bank bri':
        return 'BRI';
      case 'bni':
      case 'bank bni':
        return 'BNI';
      case 'mandiri':
      case 'bank mandiri':
        return 'Mandiri';
      case 'seabank':
      case 'sea bank':
        return 'SeaBank';
      case 'blu':
      case 'blu bca':
        return 'blu';
      case 'jenius':
      case 'bank btpn':
        return 'Jenius';
      case 'bsi':
      case 'bank bsi':
        return 'BSI';
      case 'cimb':
      case 'cimb niaga':
        return 'CIMB Niaga';
      case 'permata':
      case 'bank permata':
        return 'Permata';
      case 'gopay':
      case 'go-pay':
      case 'gojek':
        return 'Gojek';
      case 'ovo':
        return 'OVO';
      case 'dana':
        return 'Dana';
      case 'shopeepay':
      case 'shopee pay':
      case 'spay':
        return 'ShopeePay';
      case 'linkaja':
      case 'link aja':
        return 'LinkAja';
      case 'cash':
      case 'tunai':
      case 'dompet':
        return 'Dompet Utama';
      default:
        return clean.split(' ').map((w) => w.isNotEmpty ? w[0].toUpperCase() + w.substring(1) : '').join(' ');
    }
  }

  /// Membersihkan teks kalimat menjadi catatan (note) yang ringkas (mis: "Bensin", "Mi ayam serta es teh")
  String _extractNote(String segment, String intentType, String? contact, [String? wallet, String? toWallet]) {
    var note = segment.trim();

    // 1. Buang semua format hashtag atau tag metadata (misal: # Shopping, #Daily Life, dsb.)
    note = note.replaceAll(RegExp(r'#\s*[\w\s&-]+', caseSensitive: false), ' ').trim();

    // 2. Buang tag kategori Mind Space umum yang sering tertinggal di ujung / tengah
    note = note.replaceAll(RegExp(r'\b(?:Shopping|Daily Life|Food & Drink|Finance|Personal|Work|Life|Remarks)\b', caseSensitive: false), ' ').trim();

    // 3. Buang klausa nominal di mana pun berada (misal: "sebesar Rp25.000", "Rp 25.000", "25rb", "50k", dsb.)
    note = note.replaceAll(RegExp(r'\s*(?:sebesar|sejumlah|senilai|seharga|nominal|total|harga)?\s*(?:Rp\.?\s*)?\d[\d.,]*\s*(?:juta|jt|million|ribu|rb|k)?', caseSensitive: false), ' ').trim();

    // 4. Khusus transfer: bersihkan kata kerja transfer dan entitas wallet
    if (intentType == 'transfer') {
      note = note.replaceAll(RegExp(r'\b(?:transfer|pindah(?:kan)?|kirim(?:kan)?|tf|top\s*up|topup|isi\s+saldo)\s+(?:uang|saldo|dana)?', caseSensitive: false), ' ').trim();
      note = note.replaceAll(RegExp(r'\b(?:dari|ke|pakai|pake|via|lewat|menggunakan)\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?[A-Za-z0-9_]+', caseSensitive: false), ' ').trim();
      if (toWallet != null && toWallet.isNotEmpty) {
        note = note.replaceAll(RegExp('\\b${RegExp.escape(toWallet)}\\b', caseSensitive: false), ' ').trim();
      }
    }

    // 5. Buang klausa metode pembayaran / wallet (misal: "dengan jago", "pakai bca", "via gopay", "pake dana", "menggunakan BNI")
    note = note.replaceAll(RegExp(r'\s*(?:dengan|pakai|pake|via|lewat|menggunakan|by|melalui|dari)\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+|kartu\s+)?[A-Za-z0-9_]+(?:\s+[A-Za-z0-9_]+)?', caseSensitive: false), ' ').trim();

    if (wallet != null && wallet.isNotEmpty) {
      note = note.replaceAll(RegExp('\\b${RegExp.escape(wallet)}\\b', caseSensitive: false), ' ').trim();
    }

    // 6. Buang sisa-sisa pola titik nominal seperti ".000" atau ",00"
    note = note.replaceAll(RegExp(r'[.,]\d{2,3}\b'), ' ').trim();

    // 7. Buang keterangan waktu umum
    note = note.replaceAll(RegExp(r'\s+(?:pada\s+)?(?:kemarin|tadi|semalam|hari ini|siang ini|pagi ini|malam ini|sore ini)(?:\s+(?:pagi|siang|sore|malam))?', caseSensitive: false), ' ').trim();

    // 8. Buang kata sambung & kata kerja aksi di awal kalimat berulang kali
    var prev = '';
    while (prev != note) {
      prev = note;
      note = note.replaceFirst(RegExp(r'^(?:dan|serta|lalu|kemudian|terus|setelah itu)\s+', caseSensitive: false), '').trim();
      note = note.replaceFirst(RegExp(r'^(?:pembelian|beli|membeli|bayar|membayar|pembayaran|isi|order|pesan|jajan|belanja|dapat|terima|kirim)\s+', caseSensitive: false), '').trim();
    }

    // 9. Bersihkan sisa tanda baca liar di tengah atau ujung (misal "jus alpukat . " -> "jus alpukat")
    note = note.replaceAll(RegExp(r'\s+[.,;:!?]+\s*'), ' ');
    note = note.replaceAll(RegExp(r'^[^\w]+|[^\w]+$'), ' ').trim();

    // 10. Kompres spasi ganda
    note = note.replaceAll(RegExp(r'\s+'), ' ');

    // 11. Capitalize huruf pertama & fallback cerdas
    if (note.isEmpty) {
      switch (intentType) {
        case 'hutang':
          return 'Hutang ke ${contact ?? 'seseorang'}';
        case 'piutang':
          return 'Piutang ke ${contact ?? 'seseorang'}';
        case 'transfer':
          if (toWallet != null && toWallet.isNotEmpty) {
            return 'Transfer ke $toWallet';
          }
          return 'Transfer dana';
        case 'income':
          return 'Pemasukan';
        default:
          return 'Pengeluaran';
      }
    }

    return note[0].toUpperCase() + note.substring(1);
  }
