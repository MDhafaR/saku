import '../models/voice_intent_model.dart';

/// Service untuk mengekstrak entitas finansial dari teks natural bahasa Indonesia
/// (baik dari transkripsi suara Mind Space, teks input, maupun hasil OCR gambar).
class SmartTransactionParser {
  /// Entry point utama: mem-parsing teks mentah menjadi daftar [VoiceIntentModel]
  List<VoiceIntentModel> parse(String rawText) {
    if (rawText.trim().isEmpty) return [];

    // 1. Ekstrak teks inti jika terdapat format Mind Space Card
    final cleanedText = _extractCoreTranscription(rawText);

    // 2. Partisi teks berdasarkan deteksi nominal (multi-transaksi)
    final segments = _splitIntoTransactionSegments(cleanedText);

    final results = <VoiceIntentModel>[];

    for (final segment in segments) {
      final parsed = _parseSingleSegment(segment);
      if (parsed != null) {
        results.add(parsed);
      }
    }

    return results;
  }

  /// Mengekstrak bagian transkripsi jika teks berasal dari export/kartu Mind Space
  String _extractCoreTranscription(String text) {
    final lines = text.split('\n');
    final transcriptionIndex = lines.indexWhere(
      (line) => RegExp(r'^(?:#+\s*)?(?:Transcription|Transkripsi)\b', caseSensitive: false).hasMatch(line.trim()),
    );

    if (transcriptionIndex != -1) {
      final relevantLines = <String>[];
      for (var i = transcriptionIndex + 1; i < lines.length; i++) {
        final line = lines[i].trim();
        // Berhenti jika menemui hashtag, tags Mind Space, remarks, source, atau footer
        if (line.startsWith('#') ||
            RegExp(r'^(?:Shopping|Daily Life|Food & Drink|Finance|Personal|Work|Life|Remarks|Generated by|Ask questions)\b', caseSensitive: false).hasMatch(line) ||
            line.toLowerCase().startsWith('source:')) {
          break;
        }
        if (line.isNotEmpty) {
          relevantLines.add(line);
        }
      }
      if (relevantLines.isNotEmpty) {
        return _cleanNoise(relevantLines.join(' '));
      }
    }

    // Jika bukan format kartu Mind Space, gunakan teks asli yang dibersihkan dari noise/hashtag
    return _cleanNoise(text);
  }

  /// Membersihkan noise seperti hashtag dan metadata Mind Space dari teks
  String _cleanNoise(String text) {
    var cleaned = text;
    // Buang baris atau potongan hashtag (# Shopping, #Daily Life, dsb.)
    cleaned = cleaned.replaceAll(RegExp(r'#\s*[\w\s&-]+', caseSensitive: false), ' ');
    // Buang footer teks Mind Space jika ada
    cleaned = cleaned.replaceAll(RegExp(r'\b(?:Remarks|Generated by|Ask questions)\b.*$', caseSensitive: false), ' ');
    return cleaned.trim();
  }

  /// Memecah teks menjadi segmen-segmen transaksi independen
  List<String> _splitIntoTransactionSegments(String text) {
    // Cari semua posisi kemunculan nominal uang di dalam teks
    final amountMatches = _findAmountMatches(text);

    if (amountMatches.length <= 1) {
      return [text];
    }

    final segments = <String>[];
    var lastCutIndex = 0;

    for (var i = 0; i < amountMatches.length - 1; i++) {
      final currentMatch = amountMatches[i];
      final nextMatch = amountMatches[i + 1];

      // Cari kata sambung pemisah antara match saat ini dan match berikutnya
      final betweenText = text.substring(currentMatch.end, nextMatch.start);
      final splitRegex = RegExp(r'\b(?:dan(?:\s+pembelian|\s+beli|\s+bayar|\s+transfer)?|serta(?:\s+pembelian|\s+beli)?|lalu|kemudian|terus|setelah itu)\b|[,\n;]', caseSensitive: false);
      final splitMatch = splitRegex.firstMatch(betweenText);

      int cutIndex;
      if (splitMatch != null) {
        cutIndex = currentMatch.end + splitMatch.start;
      } else {
        cutIndex = currentMatch.end + (betweenText.length ~/ 2);
      }

      final segment = text.substring(lastCutIndex, cutIndex).trim();
      if (segment.isNotEmpty) {
        segments.add(segment);
      }
      lastCutIndex = cutIndex;
    }

    final remaining = text.substring(lastCutIndex).trim();
    if (remaining.isNotEmpty) {
      segments.add(remaining);
    }

    return segments;
  }

  /// Menemukan semua match nominal dalam teks
  List<Match> _findAmountMatches(String text) {
    // Format: Rp25.000, Rp 25.000, 25.000, 25rb, 25ribu, 25k, 1.5jt, 1,5 juta
    final amountPattern = RegExp(
      r'(?:Rp\.?\s*)?\b\d{1,3}(?:\.\d{3})+(?:,\d+)?\b|(?:Rp\.?\s*)?\b\d+(?:[.,]\d+)?\s*(?:juta|jt|million|ribu|rb|k)\b|(?:Rp\.?\s*)\d+\b',
      caseSensitive: false,
    );
    return amountPattern.allMatches(text).toList();
  }

  /// Mem-parsing satu segmen kalimat menjadi satu [VoiceIntentModel]
  VoiceIntentModel? _parseSingleSegment(String segment) {
    final cleanSegment = segment.trim();
    if (cleanSegment.isEmpty) return null;

    final amount = _extractAmount(cleanSegment);
    final lower = cleanSegment.toLowerCase();

    // ── 1. Deteksi Hutang / Piutang ──────────────────────────────────────────
    // Kasus Hutang: pinjam dari [nama], ngutang ke [nama], dapat pinjaman dari [nama]
    final debtRegex = RegExp(
      r'\b(?:pinjam\s+(?:uang\s+)?dari|ngutang\s+ke|hutang\s+(?:ke|dari)|dapat\s+pinjaman\s+dari)\s+([A-Za-z0-9_\s]+?)(?:\s+sebesar|\s+sejumlah|\s+senilai|\s+sebanyak|\s+sebesar\s+rp|\s+rp|\s+\d|\s+buat|\s+untuk|$)',
      caseSensitive: false,
    );
    final debtMatch = debtRegex.firstMatch(cleanSegment);
    if (debtMatch != null) {
      final contact = _cleanContactName(debtMatch.group(1));
      return VoiceIntentModel(
        feature: 'hutang_piutang',
        type: 'hutang',
        amount: amount,
        contactName: contact,
        note: _extractNote(cleanSegment, 'hutang', contact),
      );
    }

    // Kasus Piutang: meminjamkan ke [nama], pinjamkan ke [nama], kasih pinjam ke [nama], dipinjam oleh [nama]
    final loanRegex = RegExp(
      r'\b(?:meminjamkan\s+(?:uang\s+)?ke|pinjamkan\s+ke|kasih\s+pinjam\s+ke|pinjami|dipinjam\s+(?:oleh|sama))\s+([A-Za-z0-9_\s]+?)(?:\s+sebesar|\s+sejumlah|\s+senilai|\s+sebanyak|\s+sebesar\s+rp|\s+rp|\s+\d|\s+buat|\s+untuk|$)',
      caseSensitive: false,
    );
    final loanMatch = loanRegex.firstMatch(cleanSegment);
    if (loanMatch != null) {
      final contact = _cleanContactName(loanMatch.group(1));
      return VoiceIntentModel(
        feature: 'hutang_piutang',
        type: 'piutang',
        amount: amount,
        contactName: contact,
        note: _extractNote(cleanSegment, 'piutang', contact),
      );
    }

    // Kasus Piutang alternatif: "[Nama] pinjam uang ke saya"
    final altLoanRegex = RegExp(
      r'\b([A-Za-z0-9_]+)\s+pinjam\s+(?:uang\s+)?(?:ke\s+saya|sama\s+saya)',
      caseSensitive: false,
    );
    final altLoanMatch = altLoanRegex.firstMatch(cleanSegment);
    if (altLoanMatch != null) {
      final contact = _cleanContactName(altLoanMatch.group(1));
      return VoiceIntentModel(
        feature: 'hutang_piutang',
        type: 'piutang',
        amount: amount,
        contactName: contact,
        note: _extractNote(cleanSegment, 'piutang', contact),
      );
    }

    // ── 2. Deteksi Transfer Antar Dompet vs Pemasukan ──────────────────────
    final isIncome = _isIncomeIntent(lower);

    if (!isIncome) {
      // Pola 1: [transfer/pindah/kirim] [uang/saldo/dana] [dari] [From] ke [To]
      // Contoh: "Transfer uang dari Jago ke BNI sebesar Rp226.000", "Pindah dana dari BCA ke Gopay", "Tf uang Jago ke BNI"
      final transferFromToRegex = RegExp(
        r'\b(?:transfer|pindah(?:kan)?|kirim(?:kan)?|tf)\s+(?:uang\s+|saldo\s+|dana\s+)?(?:sebesar\s+[\d.,\s\w]+|\d+[\d.,\w]*\s+)?(?:dari\s+)?(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)\s+ke\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)',
        caseSensitive: false,
      );

      // Pola 2: [transfer/pindah/kirim] [uang/saldo/dana] ke [To] [dari/pakai/via] [From]
      // Contoh: "Transfer uang ke BNI dari Jago", "Transfer ke BNI pakai BCA 50rb"
      final transferToFromRegex = RegExp(
        r'\b(?:transfer|pindah(?:kan)?|kirim(?:kan)?|tf)\s+(?:uang\s+|saldo\s+|dana\s+)?(?:sebesar\s+[\d.,\s\w]+|\d+[\d.,\w]*\s+)?ke\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)\s+(?:dari|pakai|pake|via|lewat|menggunakan)\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)',
        caseSensitive: false,
      );

      // Pola 3: [top up/isi saldo] [To] [dari/pakai/via] [From]
      // Contoh: "Top up Dana dari Jago", "Topup gopay 50rb pakai BCA", "Isi saldo ShopeePay via Mandiri"
      final topupFromRegex = RegExp(
        r'\b(?:top\s*up|topup|isi\s+saldo)\s+(?:ke\s+)?(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)(?:\s+(?:sebesar\s+[\d.,\s\w]+|\d+[\d.,\w]*))?\s*(?:dari|pakai|pake|via|lewat|menggunakan)\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)',
        caseSensitive: false,
      );

      // Pola 4: [top up/isi saldo] [To] (tanpa asal)
      // Contoh: "Top up Gopay 50rb", "Isi saldo ShopeePay 100k"
      final topupToOnlyRegex = RegExp(
        r'\b(?:top\s*up|topup|isi\s+saldo)\s+(?:ke\s+)?(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)',
        caseSensitive: false,
      );

      // Pola 5: [transfer/pindah/kirim] [uang/saldo/dana] ke [To] (tanpa asal)
      // Contoh: "Transfer uang ke BNI sebesar 200rb", "Pindah saldo ke BCA"
      final transferToOnlyRegex = RegExp(
        r'\b(?:transfer|pindah(?:kan)?|kirim(?:kan)?|tf)\s+(?:uang\s+|saldo\s+|dana\s+)?(?:sebesar\s+[\d.,\s\w]+|\d+[\d.,\w]*\s+)?ke\s+(?:rekening\s+|bank\s+|dompet\s+|akun\s+)?([A-Za-z0-9_]+)',
        caseSensitive: false,
      );

      final matchFromTo = transferFromToRegex.firstMatch(cleanSegment);
      final matchToFrom = transferToFromRegex.firstMatch(cleanSegment);
      final matchTopupFrom = topupFromRegex.firstMatch(cleanSegment);
      final matchTopupToOnly = topupToOnlyRegex.firstMatch(cleanSegment);
      final matchTransferToOnly = transferToOnlyRegex.firstMatch(cleanSegment);

      final isTransferPhrase = RegExp(
        r'\b(?:transfer\s+uang|pindah\s+uang|pindah\s+saldo|transfer\s+saldo|kirim\s+uang|kirim\s+saldo|tf\s+uang|top\s*up|isi\s+saldo)\b',
        caseSensitive: false,
      ).hasMatch(cleanSegment);

      if (matchFromTo != null || matchToFrom != null || matchTopupFrom != null || matchTopupToOnly != null || matchTransferToOnly != null || isTransferPhrase) {
        String? fromW;
        String? toW;

        if (matchFromTo != null) {
          fromW = _cleanWalletCandidate(matchFromTo.group(1));
          toW = _cleanWalletCandidate(matchFromTo.group(2));
        } else if (matchToFrom != null) {
          toW = _cleanWalletCandidate(matchToFrom.group(1));
          fromW = _cleanWalletCandidate(matchToFrom.group(2));
        } else if (matchTopupFrom != null) {
          toW = _cleanWalletCandidate(matchTopupFrom.group(1));
          fromW = _cleanWalletCandidate(matchTopupFrom.group(2));
        } else if (matchTopupToOnly != null) {
          toW = _cleanWalletCandidate(matchTopupToOnly.group(1));
        } else if (matchTransferToOnly != null) {
          toW = _cleanWalletCandidate(matchTransferToOnly.group(1));
        }

        // Jika fromW belum terdeteksi dari pola khusus, cari dari klausa preposisi "dari [wallet]" atau wallet umum
        fromW ??= _extractSourceWalletForTransfer(cleanSegment, excludedWallet: toW);

        final normFrom = fromW != null ? _normalizeWalletName(fromW) : null;
        final normTo = toW != null ? _normalizeWalletName(toW) : null;

        return VoiceIntentModel(
          feature: 'transfer',
          amount: amount,
          fromWallet: normFrom,
          toWallet: normTo,
          note: _extractNote(cleanSegment, 'transfer', null, normFrom, normTo),
        );
      }
    }

    // ── 3. Deteksi Pemasukan (Income) ─────────────────────────────────────────
    if (isIncome) {
      final category = _detectCategory(lower, isIncome: true);
      final wallet = _extractWallet(cleanSegment);
      return VoiceIntentModel(
        feature: 'transaksi',
        type: 'income',
        amount: amount,
        category: category,
        wallet: wallet,
        note: _extractNote(cleanSegment, 'income', null, wallet),
      );
    }

    // ── 4. Default: Pengeluaran (Expense) ────────────────────────────────────
    final category = _detectCategory(lower, isIncome: false);
    final wallet = _extractWallet(cleanSegment);
    return VoiceIntentModel(
      feature: 'transaksi',
      type: 'expense',
      amount: amount,
      category: category,
      wallet: wallet,
      note: _extractNote(cleanSegment, 'expense', null, wallet),
    );
  }

  /// Ekstraksi nilai nominal double dari kalimat
  double? _extractAmount(String text) {
    // 1. Kasus dengan satuan juta: "1.5 jt", "2 juta", "1,5juta"
    final jtMatch = RegExp(r'(\d+(?:[.,]\d+)?)\s*(?:juta|jt|million)\b', caseSensitive: false).firstMatch(text);
    if (jtMatch != null) {
      final numStr = jtMatch.group(1)!.replaceAll(',', '.');
      final val = double.tryParse(numStr);
      if (val != null) return val * 1000000;
    }

    // 2. Kasus dengan satuan ribu: "25rb", "25 ribu", "50k", "10.5 rb"
    final rbMatch = RegExp(r'(\d+(?:[.,]\d+)?)\s*(?:ribu|rb|k)\b', caseSensitive: false).firstMatch(text);
    if (rbMatch != null) {
      final numStr = rbMatch.group(1)!.replaceAll(',', '.');
      final val = double.tryParse(numStr);
      if (val != null) return val * 1000;
    }

    // 3. Format ribuan bertitik: "Rp25.000", "25.000", "1.500.000"
    final thousandMatch = RegExp(r'(?:Rp\.?\s*)?(\d{1,3}(?:\.\d{3})+(?:,\d+)?)', caseSensitive: false).firstMatch(text);
    if (thousandMatch != null) {
      final cleanNum = thousandMatch.group(1)!.replaceAll('.', '').replaceAll(',', '.');
      final val = double.tryParse(cleanNum);
      if (val != null) return val;
    }

    // 4. Format angka polos: "Rp 25000", "sebesar 50000"
    final plainMatch = RegExp(r'(?:Rp\.?\s*|sebesar\s+|seharga\s+|sejumlah\s+)(\d+)\b', caseSensitive: false).firstMatch(text);
    if (plainMatch != null) {
      return double.tryParse(plainMatch.group(1)!);
    }

    // 5. Fallback angka apa saja di atas 100
    final anyNumMatch = RegExp(r'\b(\d{4,})\b').firstMatch(text);
    if (anyNumMatch != null) {
      return double.tryParse(anyNumMatch.group(1)!);
    }

    return null;
  }

  /// Cek apakah kalimat mengindikasikan pemasukan
  bool _isIncomeIntent(String text) {
    const incomeKeywords = [
      'gaji',
      'salary',
      'upah',
      'honor',
      'penghasilan',
      'pendapatan',
      'pemasukan',
      'income',
      'terima uang',
      'dapat uang',
      'dapat transfer',
      'ditransfer',
      'dikirimkan uang',
      'dikirim uang',
